def generate_sdf(atoms, bonds=None, molecule_name="Molecule"):
    """
    Convert atomic coordinates and types to an SDF format string.
    
    atoms: List of dictionaries with 'type' and 'coords'.
    bonds: List of tuples defining bonds (optional).
    molecule_name: Name of the molecule.
    
    Returns:
    str: SDF formatted string.
    """
    sdf_lines = []
    
    # Header block
    sdf_lines.append(molecule_name)
    sdf_lines.append("  Generated by Python")
    sdf_lines.append("")
    
    # Atom and bond counts
    num_atoms = len(atoms)
    num_bonds = len(bonds) if bonds else 0
    sdf_lines.append(f"{num_atoms:>3}{num_bonds:>3}  0  0  0  0            999 V2000")
    
    # Atomic block
    for atom in atoms:
        x, y, z = atom["coords"]
        atom_type = atom["type"]
        sdf_lines.append(f"{x:>10.4f}{y:>10.4f}{z:>10.4f} {atom_type:<3} 0  0  0  0  0  0  0  0")
    
    # Bond block (optional)
    if bonds:
        for bond in bonds:
            atom1, atom2, bond_type = bond
            sdf_lines.append(f"{atom1:>3}{atom2:>3}{bond_type:>3}  0  0  0  0")
    
    # End of molecule
    sdf_lines.append("M  END")
    sdf_lines.append("$$$$")
    
    return "\n".join(sdf_lines)

